-- Core schema for user accounts, learning profiles, and token revocation.
-- Mirrors the JPA entities exactly so spring.jpa.hibernate.ddl-auto=validate passes.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255)                 NOT NULL,
    password_hash VARCHAR(255)                 NOT NULL,
    display_name  VARCHAR(255),
    created_at    TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE learning_profiles (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT                        NOT NULL,
    current_stage         INTEGER                       NOT NULL,
    program_start_date    TIMESTAMP(6) WITH TIME ZONE,
    total_practice_minutes INTEGER                       NOT NULL,
    CONSTRAINT uk_learning_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_learning_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE learning_profile_unlocked_stages (
    learning_profile_id BIGINT NOT NULL,
    stage               INTEGER,
    CONSTRAINT fk_unlocked_stages_profile FOREIGN KEY (learning_profile_id)
        REFERENCES learning_profiles (id)
);

CREATE TABLE revoked_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti        VARCHAR(255)                NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_revoked_token_jti UNIQUE (jti)
);
